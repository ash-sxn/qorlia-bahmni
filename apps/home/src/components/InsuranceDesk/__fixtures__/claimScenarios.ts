import { CaseDocument, InsuranceCase, IsoDateTime, Paise } from '../types';

const rupees = (value: number): Paise => value * 100;

const november = (day: number, time = '10:00'): IsoDateTime =>
  `2026-11-${String(day).padStart(2, '0')}T${time}:00+05:30`;

const document = (
  type: string,
  stage: CaseDocument['stage'],
  state: CaseDocument['state'] = 'sent',
): CaseDocument => ({ type: `Synthetic ${type}`, stage, state });

/** The papers a hospital sends with a claim, as listed in IRDAI Part D (circular of 27 May 2019). */
